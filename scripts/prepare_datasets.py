"""Prepare inspectable, locally reproducible standard CSV datasets.
Do not replace the real California Housing or professional observational data.
"""
from pathlib import Path
import json
import numpy as np, pandas as pd, sklearn
from sklearn.datasets import (load_iris,load_wine,load_digits,load_diabetes,
                              make_blobs, make_moons)
root=Path(__file__).resolve().parents[1]
d=root/'data'; d.mkdir(exist_ok=True)
infos=[]
for name,loader in [('iris',load_iris),('wine',load_wine),('digits',load_digits),('diabetes',load_diabetes)]:
    obj=loader(as_frame=True)
    df=obj.frame.copy()
    outfile=d/f'{name}.csv'
    df.to_csv(outfile,index=False)
    infos.append(dict(name=name,sklearn_loader=loader.__name__,samples=len(obj.data),
                      features=obj.data.shape[1],label_column=obj.target.name,
                      csv=outfile.name,source='sklearn builtin',sklearn_version=sklearn.__version__))
Xm,y=make_moons(n_samples=400,noise=.08,random_state=42)
pd.DataFrame({'x1':Xm[:,0],'x2':Xm[:,1],'teaching_label':y}).to_csv(d/'synthetic_moons.csv',index=False)
infos.append(dict(name='synthetic_moons',samples=400,features=2,source='artificially generated by sklearn make_moons',seed=42,csv='synthetic_moons.csv'))
# SDSS/OGLE/Gaia/Airfoil/Sonar/Superconductivity are not bundled; use official records.
(d/'catalog.json').write_text(json.dumps(infos,ensure_ascii=False,indent=2))
print('Created',len(infos),'local CSV files, sklearn',sklearn.__version__)
